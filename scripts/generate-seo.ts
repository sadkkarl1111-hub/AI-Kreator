import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import {
  DEFAULT_IMAGE, PRIVATE_PATHS, PUBLIC_SEO_PAGES, SEO_ALIASES,
  seoStructuredData, SITE_NAME, SITE_URL, type SeoPage,
} from '../src/lib/seo.ts';

export const escapeHtml = (value: string) => value.replace(/[&<>"']/g, (character) => ({
  '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;',
})[character]!);

export function renderSeoHead(entry?: SeoPage) {
  const title = entry?.title || `Panel użytkownika | ${SITE_NAME}`;
  const description = entry?.description || 'Konto i narzędzia użytkownika Kreatora Grafik AI.';
  const image = `${SITE_URL}${entry?.image || DEFAULT_IMAGE}`;
  const url = entry ? `${SITE_URL}${entry.path}` : null;
  return [
    `<title>${escapeHtml(title)}</title>`,
    `<meta name="description" content="${escapeHtml(description)}" />`,
    `<meta name="robots" content="${entry ? 'index, follow, max-image-preview:large' : 'noindex, follow'}" />`,
    ...(url ? [`<link rel="canonical" href="${url}" />`, `<meta property="og:url" content="${url}" />`] : []),
    `<meta property="og:type" content="${entry?.article ? 'article' : 'website'}" />`,
    `<meta property="og:site_name" content="${SITE_NAME}" />`,
    '<meta property="og:locale" content="pl_PL" />',
    `<meta property="og:title" content="${escapeHtml(title)}" />`,
    `<meta property="og:description" content="${escapeHtml(description)}" />`,
    `<meta property="og:image" content="${image}" />`,
    '<meta name="twitter:card" content="summary_large_image" />',
    `<meta name="twitter:title" content="${escapeHtml(title)}" />`,
    `<meta name="twitter:description" content="${escapeHtml(description)}" />`,
    `<meta name="twitter:image" content="${image}" />`,
    ...(entry ? [`<script type="application/ld+json" data-route-seo>${JSON.stringify(seoStructuredData(entry)).replace(/</g, '\\u003c')}</script>`] : []),
  ].join('\n    ');
}

// Real public text and crawlable links are available even before JavaScript runs.
// React replaces this initial view with the interactive page (createRoot, not hydrate).
export function renderInitialContent(entry?: SeoPage) {
  if (!entry) return '';
  const link = (href: string, label: string) => `<a href="${escapeHtml(href)}">${escapeHtml(label)}</a>`;
  const article = entry.article;
  const body = article ? [
    ...article.intro.map((text) => `<p>${escapeHtml(text)}</p>`),
    ...article.sections.map((section) => `<section><h2>${escapeHtml(section.title)}</h2>${section.paragraphs.map((text) => `<p>${escapeHtml(text)}</p>`).join('')}${section.table ? `<table>${section.table.caption ? `<caption>${escapeHtml(section.table.caption)}</caption>` : ''}<thead><tr>${section.table.headers.map((cell) => `<th>${escapeHtml(cell)}</th>`).join('')}</tr></thead><tbody>${section.table.rows.map((row) => `<tr>${row.map((cell) => `<td>${escapeHtml(cell)}</td>`).join('')}</tr>`).join('')}</tbody></table>` : ''}${section.links?.map((entry) => `<p>${link(entry.href, entry.label)}</p>`).join('') || ''}</section>`),
  ].join('') : '';
  const related = PUBLIC_SEO_PAGES.filter((item) => {
    if (entry.path === '/blog') return !!item.article;
    if (entry.article) return item.article && entry.article.relatedSlugs.includes(item.article.slug);
    if (entry.path === '/' || entry.path === '/tools') return item.path.startsWith('/tools/');
    return ['/tools', '/blog', '/galeria-publiczna'].includes(item.path);
  });
  return `<main style="max-width:1100px;margin:40px auto;padding:24px;font:16px/1.7 system-ui,sans-serif"><nav>${link('/', SITE_NAME)} · ${link('/tools', 'Narzędzia')} · ${link('/blog', 'Blog')}</nav><h1>${escapeHtml(entry.heading)}</h1><p>${escapeHtml(entry.description)}</p>${body}${related.length ? `<section><h2>${entry.path === '/blog' || article ? 'Poradniki' : 'Narzędzia i inspiracje'}</h2><ul>${related.map((item) => `<li>${link(item.path, item.heading)}</li>`).join('')}</ul></section>` : ''}<noscript><p>Włącz JavaScript, aby korzystać z interaktywnych narzędzi.</p></noscript></main>`;
}

export function renderSitemap() {
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${PUBLIC_SEO_PAGES.map((entry) => `  <url><loc>${SITE_URL}${entry.path}</loc></url>`).join('\n')}\n</urlset>\n`;
}

const regexEscape = (value: string) => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
export const seoFile = (entry: SeoPage) => entry.path === '/' ? 'home.html' : `${entry.path.slice(1)}.html`;

export function renderApacheRoutes() {
  return [
    '# Generated by npm run build. Include INSIDE the DocumentRoot Directory block.',
    'RewriteEngine On',
    '# /blog also stores image assets; avoid mod_dir adding a slash to the page URL.',
    'DirectorySlash Off',
    '# Do not expose internal HTML aliases as separate public pages.',
    'RewriteCond %{ENV:REDIRECT_STATUS} ^$',
    'RewriteCond %{THE_REQUEST} "\\s/+_seo(?:[/ ?])" [NC]',
    'RewriteRule ^_seo(?:/|$) - [R=404,END]',
    'RewriteCond %{THE_REQUEST} "\\s/+index\\.html(?:[? ]|$)" [NC]',
    'RewriteRule ^index\\.html$ / [R=301,END]',
    ...Object.entries(SEO_ALIASES).map(([alias, target]) => `RewriteRule ^${regexEscape(alias.slice(1))}/?$ ${target} [R=301,END,NE]`),
    ...[...PUBLIC_SEO_PAGES.map((entry) => entry.path), ...PRIVATE_PATHS].filter((route) => route !== '/').map((route) => `RewriteRule ^${regexEscape(route.slice(1))}/$ ${route} [R=301,END,NE]`),
    ...PUBLIC_SEO_PAGES.map((entry) => `RewriteRule ^${regexEscape(entry.path.slice(1))}$ /_seo/${seoFile(entry)} [END]`),
    `RewriteRule ^(?:${PRIVATE_PATHS.map((route) => regexEscape(route.slice(1))).join('|')}|shared/[^/]+)$ /_seo/private.html [END]`,
    '# Leave actual assets intact. Missing URLs must return a real 404.',
    'RewriteCond %{REQUEST_FILENAME} !-f',
    'RewriteCond %{REQUEST_FILENAME} !-d',
    'RewriteRule ^ - [R=404,END]',
    '',
  ].join('\n');
}

export async function generateSeo(root: string) {
  const dist = path.join(root, 'dist');
  const template = await readFile(path.join(dist, 'index.html'), 'utf8');
  if (!template.includes('<!-- seo:start -->') || !template.includes('<div id="root"></div>')) throw new Error('Missing SEO template markers');
  const html = (entry?: SeoPage) => template
    .replace(/<!-- seo:start -->[\s\S]*?<!-- seo:end -->/, `<!-- seo:start -->\n    ${renderSeoHead(entry)}\n    <!-- seo:end -->`)
    .replace('<div id="root"></div>', `<div id="root">${renderInitialContent(entry)}</div>`);
  for (const entry of PUBLIC_SEO_PAGES) {
    const target = path.join(dist, '_seo', seoFile(entry));
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, html(entry));
  }
  await writeFile(path.join(dist, 'index.html'), html(PUBLIC_SEO_PAGES[0]));
  await writeFile(path.join(dist, '_seo/private.html'), html());
  await writeFile(path.join(dist, '_seo/not-found.html'), html().replace('<div id="root"></div>', '<div id="root"><main><h1>404 — Nie znaleziono strony</h1><a href="/">Wróć na stronę główną</a></main></div>'));
  await writeFile(path.join(dist, 'sitemap.xml'), renderSitemap());
  await mkdir(path.join(root, 'vps/apache'), { recursive: true });
  await writeFile(path.join(root, 'vps/apache/seo-routes.conf'), renderApacheRoutes());
  console.log(`SEO: ${PUBLIC_SEO_PAGES.length} public pages, sitemap, private noindex and 404 HTML generated.`);
}
